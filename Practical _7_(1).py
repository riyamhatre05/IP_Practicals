# Lists and Tuples: Types and Syntax

numbers = [10, 20, 30, 40, 50]
strings = ("Apple", "Banana", "Mango", "Orange")

print("list of numbers:", numbers)
print("Tuple of strings:", strings)
print("Type of list:", type(numbers))
print("Type of tuple:", type(strings))
print("List uses square brackets []")
print("Tuple uses round brackets ()")
