# Define function to process a list
def list_process(numbers):
    total = sum(numbers)  #
    largest = max(numbers)  #
    print("List:", numbers)  #
    print("sum:", total)  #
    print("largest element:", largest)  #

# Call the function multiple times with different lists
list_process([10, 20, 30, 40, 50])  #
print()  #
list_process([5, 15, 25, 35])  #
print()  #
list_process([100, 50, 75, 25])  #
