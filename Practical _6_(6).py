# Question 6: Learn array creation

import numpy as np

# using np.array ()
arr1 = np.array([1, 2, 3, 4, 5])
# using np.zeros ()
arr2 = np.zeros(5)
# Using np.ones ()
arr3 = np.ones(5)
print("Array using np.array():", arr1)
print("Array using np.zeros():", arr2)
print("Array using np.ones():", arr3)
print("\nshape:", arr1.shape)
print("Data type:", arr1.dtype)
